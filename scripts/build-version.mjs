#!/usr/bin/env node
// The build's version: the ONE place it is worked out, for the core (an MSBuild target in Yawble.Core.csproj runs
// this with --cs) and the shell (vite.config.mts imports it). scripts/release-functions.ps1 Get-BuildVersion is the same
// rule for the release script, and both are tested with the same cases.
//
//   released commit, clean tree    2026.11.12.1
//   any other commit               2026.11.12.1+dev.ee55691    (the last release before it, + the short commit)
//   before the first release       0.0.0+dev.ee55691
//   uncommitted changes            ...+dev.ee55691.dirty
//   no git (a tarball)             0.0.0+dev.unknown           (never fails the build)
//
// A release tag is v<yyyy>.<mm>.<dd>.<N> (scripts/release.ps1 makes them). The tags must have been
// fetched for a dev build to name its release (git fetch --tags); without them the build says 0.0.0+dev.<sha>.
// YAWBLE_BUILD_VERSION (and YAWBLE_BUILD_COMMIT) in the environment win: a build with no .git (a container) is told.
//
//   node scripts/build-version.mjs              prints the version
//   node scripts/build-version.mjs --json       prints {version, commit, dirty, released}
//   node scripts/build-version.mjs --cs <file>  writes the core's assembly attributes (only when they changed)
//
// packaging/build.mjs stamps the same version into the installed files: numericVersion (2026.11.14.3) for the file
// and assembly versions and the Electron app's version (dotnetVersionProperties, electronBuilderVersion).
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const RELEASE_TAG = /^v(\d{4}\.\d{2}\.\d{2}\.\d+)(?:-(\d+)-g[0-9a-f]+)?$/;
const RELEASE_VERSION = /^\d{4}\.\d{2}\.\d{2}\.\d+$/;
const DEV_VERSION = /^(\d{4}\.\d{2}\.\d{2}\.\d+|0\.0\.0)\+dev\.([0-9a-f]{7}|unknown)(\.dirty)?$/;

/** Whether a version given from outside (YAWBLE_BUILD_VERSION) has a shape this file would make: release or dev, <= 40 chars. */
export function isBuildVersion(v) {
  return typeof v === 'string' && v.length <= 40 && (RELEASE_VERSION.test(v) || DEV_VERSION.test(v));
}

export const UNKNOWN = Object.freeze({ version: '0.0.0+dev.unknown', commit: 'unknown', dirty: false, released: false });

/**
 * The version from what git said: `git describe --tags --match "v2*" --long` (empty when there is no release tag
 * before HEAD), the full commit, and whether the tree has uncommitted changes. Pure: tested with the cases above.
 */
export function buildVersion({ describe, sha, dirty }) {
  const commit = (sha ?? '').trim();
  if (!/^[0-9a-f]{7,40}$/.test(commit)) return { ...UNKNOWN };
  const short = commit.slice(0, 7);
  const m = RELEASE_TAG.exec((describe ?? '').trim());
  const release = m ? m[1] : '0.0.0';
  const distance = m ? Number(m[2] ?? '0') : -1;
  const released = !!m && distance === 0 && !dirty;
  const version = released ? release : `${release}+dev.${short}${dirty ? '.dirty' : ''}`;
  return { version, commit, dirty: !!dirty, released };
}

function git(cwd, args) {
  return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], windowsHide: true }).trim();
}

/** The version of the checkout at `dir` (git), or what the environment says, or UNKNOWN. Never throws. */
export function readBuildVersion(dir = repoRoot(), env = process.env) {
  if (env.YAWBLE_BUILD_VERSION) {
    const version = env.YAWBLE_BUILD_VERSION.trim();
    if (isBuildVersion(version)) {
      return { version, commit: (env.YAWBLE_BUILD_COMMIT ?? 'unknown').trim() || 'unknown', dirty: version.endsWith('.dirty'), released: RELEASE_VERSION.test(version) };
    }
    console.error(`build-version: ignoring YAWBLE_BUILD_VERSION=${JSON.stringify(version.slice(0, 60))}: not yyyy.mm.dd.N or <release|0.0.0>+dev.<sha>[.dirty] (at most 40 characters)`);
  }
  let sha;
  try { sha = git(dir, ['rev-parse', 'HEAD']); } catch { return { ...UNKNOWN }; }
  let describe = '';
  try { describe = git(dir, ['describe', '--tags', '--match', 'v2*', '--long']); } catch { /* no release tag yet */ }
  let dirty = false;
  try { dirty = git(dir, ['status', '--porcelain', '--untracked-files=no']).length > 0; } catch { /* treat as clean */ }
  return buildVersion({ describe, sha, dirty });
}

/** The core's generated source: assembly metadata CoreInfo reads (no type, so a build without it still compiles). */
export function csharpSource(v) {
  const s = (x) => JSON.stringify(String(x));
  return [
    '// <auto-generated>scripts/build-version.mjs; not committed.</auto-generated>',
    `[assembly: System.Reflection.AssemblyMetadata("YawbleVersion", ${s(v.version)})]`,
    `[assembly: System.Reflection.AssemblyMetadata("YawbleCommit", ${s(v.commit)})]`,
    `[assembly: System.Reflection.AssemblyMetadata("YawbleDirty", ${s(v.dirty ? 'true' : 'false')})]`,
    `[assembly: System.Reflection.AssemblyMetadata("YawbleReleased", ${s(v.released ? 'true' : 'false')})]`,
    '',
  ].join('\n');
}

/** The highest part a .NET assembly or Windows file version may have (AssemblyVersion: 65534; a Win32 VERSIONINFO part is 16 bits). */
export const MAX_VERSION_PART = 65534;

/**
 * The build's version in four-part numeric form, for Windows file Properties, the assemblies and the Electron app:
 * 2026.11.14.3 for that release; a dev build gets its last release's numbers (2026.11.14.3+dev.ee55691 -> 2026.11.14.3)
 * and a build before the first release 0.0.0.0. Leading zeros go (2026.01.05.2 -> 2026.1.5.2). Throws on a version
 * this file would not make, or a part over 65534, so a package is never stamped with a wrong number.
 */
export function numericVersion(version) {
  if (!isBuildVersion(version)) throw new Error(`not a build version: ${JSON.stringify(String(version).slice(0, 60))}`);
  const parts = version.split('+')[0].split('.').map(Number);
  while (parts.length < 4) parts.push(0);
  const big = parts.find((p) => !Number.isSafeInteger(p) || p > MAX_VERSION_PART);
  if (big !== undefined) throw new Error(`${version}: version part ${big} is over ${MAX_VERSION_PART}, the most a file version can hold`);
  return parts.join('.');
}

/**
 * The `dotnet publish` properties that stamp the build's version into every published assembly and executable:
 * Version and FileVersion the numeric form, InformationalVersion (Properties' "Product version") the build's own
 * version, as yawble-core --version prints it. The SDK would add "+<commit>" to InformationalVersion; it is off.
 */
export function dotnetVersionProperties(version) {
  const n = numericVersion(version);
  return [`-p:Version=${n}`, `-p:FileVersion=${n}`, `-p:InformationalVersion=${version}`, '-p:IncludeSourceRevisionInInformationalVersion=false'];
}

/**
 * electron-builder settings for the app's version: package.json's version in the package (Electron's app.getVersion()
 * and the macOS bundle's short version), the file version of yawble.exe and the bundle version (buildVersion), and
 * buildNumber, the fourth part of the exe's and installer's product version (electron-builder reads only three parts
 * of the version there and puts buildNumber fourth).
 */
export function electronBuilderVersion(version) {
  const n = numericVersion(version);
  return { extraMetadata: { version: n }, buildVersion: n, buildNumber: n.split('.')[3] };
}

function repoRoot() {
  return path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
}

function writeIfChanged(file, text) {
  if (existsSync(file) && readFileSync(file, 'utf8') === text) return;
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, text);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const v = readBuildVersion();
  const cs = args.indexOf('--cs');
  if (cs >= 0 && args[cs + 1]) writeIfChanged(path.resolve(args[cs + 1]), csharpSource(v));
  else if (args.includes('--json')) console.log(JSON.stringify(v));
  else console.log(v.version);
}
