/**
 * WRITES THE MATERIAL SYMBOLS NAME LIST THE HOST AND THE CLI CHECK A PLUGIN'S MONITOR HINT AGAINST.
 *
 *   npm run symbols:names
 *
 * The list is every icon `@quasar/extras` ships for Material Symbols Outlined, by the ligature name
 * the font forms it from (`exposure_neg_1`, `crop_16_9`), one per line, sorted. Nothing in it is
 * typed by hand. It lands in `cli/internal/plugin/material-symbols.txt`, the one file both read:
 * the CLI embeds it with go:embed, and Harness.Host.csproj embeds the same path as a resource.
 * `MaterialSymbolNamesTests` fails until this is run again after a font upgrade.
 *
 * WHY THE FONT IS SHAPED: `icons.json` holds export names (`symOutlinedExposureNeg1`), which lose
 * where an underscore stood next to a digit - `exposure_neg_1` and `exposure_neg1` export alike. Each
 * spelling an export allows is shaped in the full font, and the one that forms a single glyph is the
 * name. An export with none, or with more than one, stops the script rather than guess.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SourceFontPath, decompress, namesWithoutGlyph } from './icon-font.mjs';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const extras = join(web, 'node_modules/@quasar/extras');
const target = join(web, '../cli/internal/plugin/material-symbols.txt');

const Prefix = 'symOutlined';

/** `18_up_rating` is exported as `symOutlined18UpRating`, as `icon-font.mjs` maps it. */
const exportName = (/** @type {string} */ name) =>
  Prefix + name.split('_').map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join('');

/**
 * Every name that exports as `exported`: a capital always starts a new word; between a letter and a
 * digit, or two digits, an underscore may or may not stand.
 * @param {string} exported
 */
function spellings(exported) {
  const words = exported.slice(Prefix.length).split(/(?=[A-Z])/).map((word) => word.toLowerCase());
  /** @type {string[]} */
  let names = [''];

  words.forEach((word, i) => {
    const [first = '', ...rest] = word.split(/(?<=[a-z])(?=[0-9])|(?<=[0-9])(?=[a-z])|(?<=[0-9])(?=[0-9])/);
    let forms = [first];
    for (const part of rest) forms = forms.flatMap((form) => [form + part, `${form}_${part}`]);
    names = names.flatMap((name) => forms.map((form) => (i === 0 ? form : `${name}_${form}`)));
  });

  return names.filter((name) => exportName(name) === exported);
}

const version = JSON.parse(readFileSync(join(extras, 'package.json'), 'utf8')).version;
const exported = /** @type {string[]} */ (
  JSON.parse(readFileSync(join(extras, 'exports/material-symbols-outlined/icons.json'), 'utf8'))
);
const ttf = await decompress(readFileSync(SourceFontPath));

const candidates = exported.map((e) => /** @type {const} */ ([e, spellings(e)]));
const noGlyph = new Set(namesWithoutGlyph(ttf, [...new Set(candidates.flatMap(([, names]) => names))]));

const names = candidates.map(([e, spelt]) => {
  const formed = spelt.filter((name) => !noGlyph.has(name));
  if (formed.length !== 1) throw new Error(`${e}: ${formed.length} spellings form a glyph (${spelt.join(', ')})`);
  return /** @type {string} */ (formed[0]);
});

writeFileSync(
  target,
  [
    `# Material Symbols Outlined, @quasar/extras ${version}: every ligature name, one per line.`,
    '# Generated by web/scripts/material-symbol-names.mjs (npm run symbols:names). Do not edit.',
    ...[...new Set(names)].sort(),
    '',
  ].join('\n'),
);

console.log(`${names.length} names from @quasar/extras ${version} -> ${target}`);
