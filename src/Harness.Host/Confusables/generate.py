#!/usr/bin/env python3
"""Regenerate team-connections-confusables.txt from Unicode's confusables.txt (UTS #39).

Run by hand, never by the build or the tests:

    curl -sSfL -o /tmp/confusables.txt https://www.unicode.org/Public/security/latest/confusables.txt
    python3 -I src/Harness.Host/Confusables/generate.py /tmp/confusables.txt src/Harness.Host/Confusables/team-connections-confusables.txt

It keeps only the entries whose target, lower-cased, is made of the letters of "teamconnections"
(t, e, a, m, c, o, n, i, s): the only mappings TeamConnectionsMember.IsReserved can use.
"""
import sys

LETTERS = set("teamconnections")


def main(source, target):
    with open(source, encoding="utf-8-sig") as f:
        lines = f.read().splitlines()
    header = {}
    for line in lines[:20]:
        for key in ("Date", "Version"):
            if line.startswith(f"# {key}:"):
                header[key] = line.split(":", 1)[1].strip()
    if "Version" not in header:
        sys.exit("no '# Version:' line in the source")
    kept = []
    for line in lines:
        data = line.split("#", 1)[0].strip()
        if not data:
            continue
        fields = [f.strip() for f in data.split(";")]
        mapped = "".join(chr(int(h, 16)) for h in fields[1].split())
        if mapped.lower() and set(mapped.lower()) <= LETTERS:
            kept.append(line.rstrip())
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write("# team-connections-confusables.txt\n")
        f.write(f"# Unicode Version: {header['Version']}\n")
        f.write(f"# Source: https://www.unicode.org/Public/security/{header['Version']}/confusables.txt (Date: {header.get('Date', '?')})\n")
        f.write("# The entries of confusables.txt whose target, lower-cased, is made of the letters t, e, a, m, c, o, n, i, s.\n")
        f.write("# Read by TeamConnectionsMember.IsReserved (embedded in Harness.Host). Generated by generate.py beside it; do not edit by hand.\n")
        f.write("# (c) Unicode, Inc. Terms of use: https://www.unicode.org/terms_of_use.html\n")
        f.write("#\n# source ; target ; type # comment\n")
        for line in kept:
            f.write(line + "\n")
    print(f"{len(kept)} entries, Unicode {header['Version']}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("usage: generate.py <confusables.txt> <team-connections-confusables.txt>")
    main(sys.argv[1], sys.argv[2])
